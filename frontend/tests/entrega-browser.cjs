// Usa una sesión sintética emitida por entrega-postgres.test.ts. Nunca usa cuentas reales.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const base = process.env.AIP_TEST_WEB_URL || 'http://127.0.0.1:5177';
assert.equal(new URL(base).hostname, '127.0.0.1');
assert.equal(new URL(base).port, '5177');
assert.ok(process.env.AIP_TEST_SESSION_FILE, 'Falta AIP_TEST_SESSION_FILE sintético');
const session = JSON.parse(fs.readFileSync(process.env.AIP_TEST_SESSION_FILE));
const output = process.env.AIP_TEST_BROWSER_OUTPUT || '/private/tmp/aip-entrega-browser';
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.AIP_CHROMIUM_PATH ? { executablePath: process.env.AIP_CHROMIUM_PATH } : {}) });
  const errors = [];
  const page = await browser.newPage({ acceptDownloads: true });
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.addInitScript(t => localStorage.setItem('accessToken', t), session.tokens.ADMINSIS);
    const go = async p => { await page.goto(base + p); await page.waitForLoadState('networkidle'); };
    await go('/adminsis/proveedores');
    await page.getByLabel('Buscar proveedor').fill(String(session.stamp));
    await page.getByRole('button', { name: 'Ver ficha', exact: true }).click();
    await page.getByText('Insumos con referencia vigente (1)', { exact: true }).waitFor();
    assert.ok(await page.getByText('ARS/kg', { exact: true }).isVisible());
    await page.screenshot({ path: path.join(output, 'proveedor.png'), fullPage: true });
    await page.getByRole('button', { name: 'Cerrar', exact: true }).last().click();
    await go('/adminsis/insumos');
    const row = page.getByRole('row').filter({ hasText: `Insumo sintético ${session.stamp}` });
    await row.getByTitle('Acciones').click();
    await page.getByText('Ver ficha', { exact: true }).click();
    await page.getByRole('heading', { name: 'Información nutricional por 100 g de insumo' }).waitFor();
    await page.getByText('1.000 ARS/kg', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'insumo.png'), fullPage: true });
    await go(`/adminsis/pedidos/${session.pedido}`);
    assert.ok((await page.locator('body').innerText()).includes(`Fórmula sintética ${session.stamp}`));
    await page.getByRole('button', { name: 'Exportar' }).click();
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Descargar PDF' }).click();
    const download = await downloadPromise;
    await download.saveAs(path.join(output, 'orden-desde-navegador.pdf'));
    assert.ok(fs.statSync(path.join(output, 'orden-desde-navegador.pdf')).size > 1000);
    await page.screenshot({ path: path.join(output, 'orden.png'), fullPage: true });
    await go('/adminsis/depositos');
    assert.ok(!(await page.locator('body').innerText()).includes('999 / 100000'));
    await page.getByRole('button', { name: 'Movimientos', exact: true }).click();
    await page.getByRole('heading', { name: 'Últimos movimientos de cajas' }).waitFor();
    await page.screenshot({ path: path.join(output, 'movimientos.png'), fullPage: true });
    // Admin de fábrica ya puede entrar a las mismas fichas sin ampliar autorización API.
    const admin = await browser.newPage();
    await admin.addInitScript(t => localStorage.setItem('accessToken', t), session.tokens.ADMINFAB);
    await admin.goto(base + '/adminfab/proveedores'); await admin.waitForLoadState('networkidle');
    assert.ok(await admin.getByRole('heading', { name: 'Proveedores', exact: true }).isVisible());
    await admin.close();
    const venta = await browser.newPage();
    await venta.addInitScript(t => localStorage.setItem('accessToken', t), session.tokens.ENCPTOVENTA);
    await venta.goto(base + '/puntoventa/stock'); await venta.waitForLoadState('networkidle');
    assert.ok(await venta.getByText('Estantería', { exact: true }).isVisible());
    assert.ok(!(await venta.locator('body').innerText()).includes('999'));
    await venta.getByRole('button', { name: 'Registrar salida' }).click();
    const producto = venta.getByRole('combobox').first();
    await producto.selectOption(String(session.producto));
    await venta.getByRole('spinbutton').fill('1.5');
    const submit = venta.getByRole('button', { name: /Confirmar|Registrar salida/ }).last();
    await submit.click();
    assert.ok(await venta.getByText('Ingresá las unidades.', { exact: true }).isVisible());
    await venta.screenshot({ path: path.join(output, 'venta-fraccion-rechazada.png'), fullPage: true });
    await venta.close();
    await page.setViewportSize({ width: 390, height: 844 });
    await go('/adminsis/proveedores');
    await page.getByLabel('Buscar proveedor').fill(String(session.stamp));
    await page.getByRole('button', { name: 'Ver ficha', exact: true }).click();
    await page.getByText('Insumos con referencia vigente (1)', { exact: true }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.screenshot({ path: path.join(output, 'proveedor-mobile.png'), fullPage: true });
    assert.deepEqual(errors, []);
    console.log('PASS navegador: proveedor, insumo, PDF descargado, inventario por cajas, historial, ADMINFAB, Estantería, fracción rechazada y móvil 390px.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
